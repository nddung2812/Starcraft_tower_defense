const { chromium } = require(process.argv[2] || 'playwright-core');
const assert = require('node:assert/strict');
const path = require('node:path');
const os = require('node:os');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--enable-unsafe-swiftshader'] });
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.goto('http://127.0.0.1:8765/?seed=12345');
    await page.waitForFunction(() => window.game);
    await page.getByRole('button', {name:'Build my own defense'}).click();
    const results = await page.evaluate(async () => {
      const { Zergling, Shell } = await import('/src/entities.js');
      const { CELL, wavePlan } = await import('/src/config.js');
      const g = game;
      const render = g.stage.render.bind(g.stage); g.stage.render = () => {};
      const check = (ok, msg) => { if (!ok) throw Error(msg); };
      const cells = g.layout.open.filter(([x,y]) => g.grid.buildable(x,y));
      const [x,y] = cells.find(([x,y]) => Math.hypot(x-g.core.x,y-g.core.z)<12);
      g.minerals = 5000;
      check(g.placeGunner('marine',x,y), 'Marine failed'); const marine = g.gunners[0];
      const [fx,fy] = cells.find(([tx,ty]) => Math.hypot(tx-x,ty-y)>2 && Math.hypot(tx-x,ty-y)<4);
      const version = g.grid.version;
      check(g.placeGunner('falcon',fx,fy), 'Falcon deployment failed'); const falcon=g.gunners[1];
      check(g.grid.version===version && !falcon.isPlaced(g), 'Aircraft occupied ground');
      check(g.commandMove([falcon],x,y)===1,'Air movement order failed');
      for(let i=0;i<120;i++) falcon.update(0.05,g);
      check(Math.hypot(falcon.x-marine.x,falcon.z-marine.z)<0.1,'Aircraft failed to reach occupied friendly tile');
      check(g.grid.occupant(x,y)===marine,'Aircraft erased ground occupant');
      const rock = Array.from({length:g.grid.COLS*g.grid.ROWS},(_,i)=>[i%g.grid.COLS,Math.floor(i/g.grid.COLS)]).find(([tx,ty])=>g.grid.get(tx,ty)===CELL.ROCK && Math.hypot(tx-x,ty-y)<10);
      check(rock,'No nearby ridge for flight test');
      check(g.commandMove([falcon],...rock)===1,'Cannot order flight over rock');
      for(let i=0;i<150;i++) falcon.update(0.05,g);
      check(Math.hypot(falcon.x-(rock[0]+.5),falcon.z-(rock[1]+.5))<.1,'Aircraft got stuck on terrain');
      check(falcon.obj.position.y>g.heightAt(falcon.x,falcon.z)+2,'Aircraft clipped mountain');
      g.commandStop([falcon]); check(!falcon.driving,'Aircraft stop failed');
      falcon.x=x+.5; falcon.z=y+.5; falcon.update(.1,g);
      const bug = new Zergling(x+3,y+.5,'zergling',1,1); g.zerglings.push(bug); g.world.add(bug.obj);
      falcon.target=bug; falcon.fire(g);
      for(let i=0;i<20;i++) for(const t of g.tracers) if(!t.dead)t.update(.05,g);
      check(bug.hp<bug.maxHp,'Gunship cannot damage ground');
      bug.dead=true;
      const sky = new Zergling(x+3,y+.5,'skyhunter',1,1); g.zerglings.push(sky); g.world.add(sky.obj); sky.update(.05,g);
      check(falcon.acquire(g)===sky,'Gunship cannot acquire air');
      const skyHp=sky.hp; falcon.target=sky; falcon.fire(g);
      for(let i=0;i<20;i++) for(const t of g.tracers) if(!t.dead)t.update(.05,g);
      check(sky.hp<skyHp,'Gunship cannot damage air');
      check(marine.acquire(g)===sky,'Marine lost anti-air coverage');
      const shell=new Shell({x:sky.x,y:.4,z:sky.z},sky.x,sky.z,100,5); const beforeShell=sky.hp;
      shell.boom(g); check(sky.hp===beforeShell,'Ground artillery hit air');
      const [tx,ty]=cells.find(([tx,ty])=>g.grid.buildable(tx,ty) && Math.hypot(tx-x,ty-y)<6);
      g.placeGunner('tank',tx,ty);const tank=g.gunners.at(-1);
      check(!tank.orderAttack(sky,g) && tank.acquire(g)===null,'Tank acquired airborne target');
      check(!bug.preyOk(falcon,g),'Melee bug can attack aircraft');
      sky.attackCd=0; sky.spit(falcon,.05,g); const hp=falcon.hp;
      for(let i=0;i<50;i++) for(const a of g.acids) if(!a.dead)a.update(.05,g);
      check(falcon.hp<hp,'Enemy anti-air cannot damage aircraft');
      check(wavePlan(5).some(s=>s.breed==='skyhunter') && !wavePlan(4).some(s=>s.breed==='skyhunter'),'Air wave unlock incorrect');
      const antiAirDamage = hp - falcon.hp;
      g.upgradeGunner(falcon);check(falcon.tier===1,'Air upgrade failed');
      g.stage.render=render; g.stage.shake=0; g.stage.focus.set(falcon.x,0,falcon.z);g.stage.updateCamera();g.stage.render();
      return {groundDamage:bug.maxHp-bug.hp,airDamage:skyHp-sky.hp,antiAirDamage,flightHeight:falcon.altitude};
    });
    console.log('Air combat:', results);
    const point=await page.evaluate(async()=>{
      const THREE=await import('three'); const f=game.gunners.find(u=>u.kind==='falcon');const p=new THREE.Vector3(f.x,f.obj.position.y+.4,f.z).project(game.camera);const r=document.getElementById('game').getBoundingClientRect();return {x:r.left+(p.x+1)*r.width/2,y:r.top+(1-p.y)*r.height/2};
    });
    await page.mouse.click(point.x,point.y);
    assert.equal(await page.evaluate(()=>game.selected?.kind),'falcon');
    const edgePoint=await page.evaluate(async()=>{
      const THREE=await import('three');const f=game.gunners.find(u=>u.kind==='falcon');
      f.x=game.grid.COLS/2;f.z=.25;f.obj.position.set(f.x,2.6,f.z);
      game.stage.focus.set(f.x,0,f.z);game.stage.updateCamera();
      const p=new THREE.Vector3(f.x,3,f.z).project(game.camera);
      const ground=game.stage.pick(new THREE.Vector2(p.x,p.y));
      if(ground&&ground.z>=0)throw Error('Edge picking fixture did not project past map boundary');
      const r=document.getElementById('game').getBoundingClientRect();
      game.emit('selectOnly',null);
      return {x:r.left+(p.x+1)*r.width/2,y:r.top+(1-p.y)*r.height/2};
    });
    await page.mouse.click(edgePoint.x,edgePoint.y);
    assert.equal(await page.evaluate(()=>game.selected?.kind),'falcon','Aircraft at the map edge must stay selectable');
    assert.match(await page.locator('#pName').textContent(),/Kestrel/);
    await page.keyboard.press('F2');
    assert.equal(await page.evaluate(()=>game.selection.some(u=>u.kind==='falcon')),true);
    await page.screenshot({path:path.join(os.tmpdir(),'td-air.png')});
    await page.evaluate(()=>{const f=game.gunners.find(u=>u.kind==='falcon');const m=game.gunners.find(u=>u.kind==='marine');f.takeDamage(9999,game,0);if(!f.dead||f.downed||game.grid.occupant(m.tx,m.ty)!==m)throw Error('Aircraft death damaged occupancy');game.recoverHardware();if(game.gunners.length)throw Error('Aircraft missing from level recovery');});
    assert.deepEqual(errors,[]);
    console.log('PASS: ground/air damage, anti-air rules, terrain flight, occupancy, selection, upgrades, death, recovery, air-wave unlock');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
